# 六十甲子循环：第 i 项 = (i%10 干, i%12 支)
GANZHI = [(i % 10, i % 12) for i in range(60)]
_GZ_INDEX = {gz: i for i, gz in enumerate(GANZHI)}


def ganzhi_index(stem: int, branch: int) -> int:
    """干支在六十甲子中的序号（0..59）。"""
    return _GZ_INDEX[(stem, branch)]


# ───────────────────────── 月柱 / 时柱 遁法 ─────────────────────────
# 五虎遁：年上起月。以「寅月(地支=2)」的天干为基准，往后逐月 +1 干。
#   甲己之年丙作首 / 乙庚之岁戊为头 / 丙辛之年寻庚起
#   丁壬壬位顺行流 / 戊癸甲寅好追求
_MONTH_BASE_STEM = {0: 2, 1: 4, 2: 6, 3: 8, 4: 0, 5: 2, 6: 4, 7: 6, 8: 8, 9: 0}


def month_stem(year_stem: int, month_branch: int) -> int:
    """由年干与月支求月干。month_branch: 寅=2 ... 丑=1。
    偏移量按 12 个月为一周天取模（跨寅→丑边界时干支才正确）。"""
    base = _MONTH_BASE_STEM[year_stem]
    return (base + ((month_branch - 2) % 12)) % 10


# 五鼠遁：日上起时。以「子时(地支=0)」的天干为基准，往后逐时 +1 干。
#   甲己还加甲 / 乙庚丙作初 / 丙辛从戊起
#   丁壬庚子居 / 戊癸何方发，壬子是真途
_HOUR_BASE_STEM = {0: 0, 1: 2, 2: 4, 3: 6, 4: 8, 5: 0, 6: 2, 7: 4, 8: 6, 9: 8}


def hour_stem(day_stem: int, hour_branch: int) -> int:
    """由日干与时支求时干。hour_branch: 子=0 ... 亥=11。"""
    base = _HOUR_BASE_STEM[day_stem]
    return (base + hour_branch) % 10


# ───────────────────────── 年柱（立春校正）─────────────────────────
def year_ganzhi(solar_date, lichun_of_year):
    """
    八字年柱以「立春」为界，而非农历正月初一。
    若 solar_date >= 当年立春 → 取当年干支；否则取前一年干支。
    solar_date / lichun_of_year 均为 date 或 datetime（可比较）。
    返回 (stem, branch)。
    """
    y = solar_date.year
    if solar_date >= lichun_of_year:
        gz_year = y
    else:
        gz_year = y - 1
    idx = (gz_year - 4) % 60          # 公元 4 年 = 甲子
    return idx % 10, idx % 12


# ───────────────────────── 时辰 ─────────────────────────
def shichen_branch(hour: int) -> int:
    """由（真太阳时）小时求时支序号。hour: 0..23。子=0, 丑=1 ... 亥=11。"""
    h = hour % 24
    if h == 23 or h == 0:
        return 0                         # 子时
    return (h + 1) // 2                # 1,2→丑(1); 3,4→寅(2) ...


def is_late_zishi(hour: int) -> bool:
    """晚子时：23:00 之后算次日（日柱顺延一天，时支仍为子）。"""
    return hour == 23


# ───────────────────────── 十神 ─────────────────────────
def ten_god(other_stem: int, day_master: int) -> str:
    """
    以日主(day_master)为参照，求 other_stem 的十神名称。
    同我→比劫；生我→印；我生→食伤；克我→官杀；我克→财。
    阴阳同→偏/比，阴阳异→正/劫。
    """
    if other_stem == day_master:
        return "比肩" if GAN_YINYANG[other_stem] == GAN_YINYANG[day_master] else "劫财"

    ow = GAN_WUXING[day_master]
    ox = GAN_WUXING[other_stem]
    same = GAN_YINYANG[other_stem] == GAN_YINYANG[day_master]

    if PRODUCE[ox] == ow:                      # 他生我 → 印
        return "正印" if not same else "偏印"
    if PRODUCE[ow] == ox:                      # 我生他 → 食伤
        return "食神" if same else "伤官"
    if KE[ox] == ow:                           # 他克我 → 官杀
        return "正官" if not same else "七杀"
    if KE[ow] == ox:                           # 我克他 → 财
        return "正财" if not same else "偏财"
    return "未知"


# ───────────────────────── 建除十二神 ─────────────────────────
JIANCHU = ["建", "除", "满", "平", "定", "执", "破", "危", "成", "收", "开", "闭"]


def jianchu_name(month_branch: int, day_branch: int) -> str:
    """
    建除十二神：建日 = 日支与月支相同之日，之后按固定顺序递推。
    offset = (日支 - 月支) mod 12。
    """
    offset = (day_branch - month_branch) % 12
    return JIANCHU[offset]


