# ───────────────────────── 胎神方位 ─────────────────────────
# 通用胎神逐日推算法：天干分量 + 地支分量 组合。
_GAN_TAISHEN = {0: "门", 1: "户", 2: "灶", 3: "厕", 4: "房", 5: "床",
                 6: "碓磨", 7: "碓磨", 8: "仓库", 9: "仓库"}
